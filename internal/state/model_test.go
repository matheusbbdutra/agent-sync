func TestSessionStateValidationErrors(t *testing.T) {
	cases := []struct {
		name   string
		mutate func(*SessionState)
	}{
		{
			"schema_version errado",
			func(s *SessionState) { s.SchemaVersion = "9.9" },
		},
		{
			"project.name vazio",
			func(s *SessionState) { s.Project.Name = "" },
		},
		{
			"project.root vazio",
			func(s *SessionState) { s.Project.Root = "" },
		},
		{
			"session.id vazio",
			func(s *SessionState) { s.Session.ID = "" },
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			s := newTestSessionState()
			tc.mutate(&s)
			if err := s.validate(); err == nil {
				t.Errorf("esperava erro de validação, veio nil")
			}
		})
	}
}

