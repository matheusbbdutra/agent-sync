// TestSessionStateWriteConcurrentLockless verifica que dois writes paralelos
// sem o lock opcional (default) completam sem corromper o arquivo. Atomic
// rename + tmpfile único por PID+nanoTimestamp garantem que o último vence.
func TestSessionStateWriteConcurrentLockless(t *testing.T) {
	root := t.TempDir()
	t.Setenv(SessionStateLockEnvVar, "")

	const writers = 4
	errs := make(chan error, writers)
	for i := 0; i < writers; i++ {
		i := i
		go func() {
			s := newTestSessionState()
			s.Session.ID = "sess-concurrent-" + string(rune('A'+i))
			errs <- WriteSessionState(root, s)
		}()
	}
	for i := 0; i < writers; i++ {
		if err := <-errs; err != nil {
			t.Errorf("writer %d falhou: %v", i, err)
		}
	}

	loaded, err := ReadSessionState(root)
	if err != nil {
		t.Fatalf("read após writes concorrentes: %v", err)
	}
	if !strings.HasPrefix(loaded.Session.ID, "sess-concurrent-") {
		t.Errorf("ID não é de um dos writers concorrentes: %q", loaded.Session.ID)
	}
}

// TestAcquireSessionLockBlocksUntilReleased verifica o lock opcional
// (AGENT_SYNC_SESSION_LOCK=1). Goroutine A adquire e segura; B bloqueia
// até A liberar.
func TestAcquireSessionLockBlocksUntilReleased(t *testing.T) {
	root := t.TempDir()

	releaseA, err := acquireSessionLock(root)
	if err != nil {
		t.Fatalf("A acquire: %v", err)
	}

	if _, err := os.Stat(lockPath(root)); err != nil {
		t.Fatalf("lockfile não criado: %v", err)
	}

	bStarted := make(chan struct{})
	bDone := make(chan error, 1)
	go func() {
		close(bStarted)
		releaseB, err := acquireSessionLock(root)
		bDone <- err
		if releaseB != nil {
			releaseB()
		}
	}()

	<-bStarted
	select {
	case <-bDone:
		t.Fatal("B conseguiu lock enquanto A segurava — não bloqueou")
	case <-time.After(50 * time.Millisecond):
	}

	releaseA()

	select {
	case err := <-bDone:
		if err != nil {
			t.Errorf("B falhou após A liberar: %v", err)
		}
	case <-time.After(SessionStateLockTimeout):
		t.Fatal("B não conseguiu lock após A liberar dentro do timeout")
	}

	if _, err := os.Stat(lockPath(root)); !os.IsNotExist(err) {
		t.Errorf("lockfile não foi removido após release: err=%v", err)
	}
}

func stripRenderTimestamp(s string) string {
	lines := strings.Split(s, "\n")
	var kept []string
	for _, line := range lines {
		if strings.HasPrefix(line, "> Renderizado por") {
			continue
		}
		if strings.HasPrefix(line, "- Última atualização:") {
			continue
		}
		kept = append(kept, line)
	}
	return strings.Join(kept, "\n")
}
